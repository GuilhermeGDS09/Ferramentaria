def conectar():
    return sqlite3.connect(DB)

def importar_dados():
    con = conectar()
    cur = con.cursor()
    linhas_importadas = 0

    # Lendo diretamente da variável de texto acima
    arquivo_virtual = io.StringIO(DADOS_CSV.strip())
    leitor = csv.DictReader(arquivo_virtual, delimiter=',')

    for linha in leitor:
        try:
            codigo_peca = linha['Código peça'].strip()
            desc_peca = linha['Descrição'].strip()
            maquina_nome = linha['Máquina'].strip()
            numero_os = linha['OS'].strip()
            quantidade = linha['Quant.'].strip()
            data_solicitacao = linha['Data solicitação'].strip()
            prioridade = linha['Prioridade'].strip()
            status_planilha = linha['Status'].strip()

            if not numero_os or not codigo_peca:
                continue

            # Ajuste de Status
            status_db = "Aberta"
            if "PRONTA" in status_planilha.upper() or "RECEBIDO" in status_planilha.upper() or "FINALIZADO" in status_planilha.upper():
                status_db = "Concluída"

            # 1. Máquina
            cur.execute("SELECT id FROM maquinas WHERE nome = ?", (maquina_nome,))
            maq = cur.fetchone()
            if not maq:
                cur.execute("INSERT INTO maquinas(nome, tipo) VALUES (?, 'Importada')", (maquina_nome,))
                maquina_id = cur.lastrowid
            else:
                maquina_id = maq[0]

            # 2. Peça
            cur.execute("SELECT id FROM pecas WHERE codigo = ?", (codigo_peca,))
            peca = cur.fetchone()
            if not peca:
                cur.execute("INSERT INTO pecas(codigo, descricao) VALUES (?, ?)", (codigo_peca, desc_peca))
                peca_id = cur.lastrowid
                
                # Cria operação padrão (60min) para a peça
                cur.execute("""
                    INSERT INTO operacoes(peca_id, sequencia, descricao, maquina_id, tempo_min) 
                    VALUES (?, 1, 'Operação Padrão', ?, 60)
                """, (peca_id, maquina_id))
            else:
                peca_id = peca[0]

            # Formatar a data para o banco
            try:
                data_formatada = datetime.strptime(data_solicitacao, '%m/%d/%Y').strftime('%Y-%m-%d')
            except ValueError:
                data_formatada = date.today().strftime('%Y-%m-%d')

            # 3. Ordem
            cur.execute("SELECT id FROM ordens WHERE numero = ?", (numero_os,))
            if not cur.fetchone():
                qtd_int = int(quantidade) if quantidade.isdigit() else 1
                cur.execute("""
                    INSERT INTO ordens(numero, peca_id, quantidade, data_inicio, prioridade, status) 
                    VALUES (?, ?, ?, ?, ?, ?)
                """, (numero_os, peca_id, qtd_int, data_formatada, prioridade, status_db))
                linhas_importadas += 1

        except Exception as e:
            print(f"Erro na OS {linha.get('OS', '')}: {e}")

    con.commit()
    con.close()
    print(f"\n✅ SUCESSO ABSOLUTO! {linhas_importadas} Ordens de Produção foram cadastradas no banco de dados.\n")

if __name__ == "__main__":
    importar_dados()